"""
tools/notification-icons/build_icons.py

Turns the SVGs in ./svg/ into the Android VectorDrawables the ongoing workout
notification uses (Ergnova/Platforms/Android/Resources/drawable/ic_stat_*.xml).

Why this exists: Android can't load an .svg file as a notification icon — it
needs VectorDrawable XML — but the SVG is the format you actually want to edit
and preview. So the SVGs here are the source of truth, and the XML is generated
from them and checked in (the MAUI build just picks the XML up as a normal
Android resource; nothing at build time runs this script).

    python3 tools/notification-icons/build_icons.py           # (re)generate
    python3 tools/notification-icons/build_icons.py --check   # fail if XML is stale (CI-friendly)

Rules an SVG here has to follow (the script enforces them, because the failure
mode otherwise is an icon that looks right in a browser and wrong on a phone):

  * viewBox "0 0 24 24", exactly ONE <path>, filled — no strokes, no transforms,
    no <circle>/<rect> (write them as path data instead).
  * Holes must be wound OPPOSITE to their outer contour. The manifest's minSdk is
    23, and VectorDrawable's android:fillType="evenOdd" only exists from API 24,
    so every icon has to render correctly under the default nonzero fill rule.
    (In an SVG, sweep-flag 1 is clockwise on screen; a hole uses sweep-flag 0.)
  * The fill colour is irrelevant — Android draws a notification's small icon as
    a white/alpha silhouette regardless, and the in-notification icons are
    tinted at runtime (see BackgroundNotificationViews.cs) — so the XML is always
    plain white.

File names map to resource names: svg/power.svg -> R.drawable.ic_stat_power,
i.e. `Resource.Drawable.ic_stat_power` in C#. Use [a-z0-9_] only.
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SVG_DIR = HERE / "svg"
OUT_DIR = HERE.parent.parent / "Ergnova" / "Platforms" / "Android" / "Resources" / "drawable"

PATH_RE = re.compile(r"<path\b[^>]*?\bd=\"([^\"]+)\"[^>]*?/?>", re.S)
ALLOWED_PATH_CHARS = re.compile(r"^[MmLlHhVvCcSsQqTtAaZz0-9eE.,\s+-]+$")

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/notification-icons/build_icons.py from svg/{name}.svg — edit the SVG, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="{path}" />
</vector>
"""


def convert(svg_file: Path) -> str:
    name = svg_file.stem
    if not re.fullmatch(r"[a-z0-9_]+", name):
        sys.exit(f"{svg_file.name}: file name must be [a-z0-9_] only (it becomes an Android resource name)")
    svg = svg_file.read_text(encoding="utf-8")

    if not re.search(r'viewBox="0 0 24 24"', svg):
        sys.exit(f'{svg_file.name}: viewBox must be exactly "0 0 24 24"')
    for banned in ("<circle", "<rect", "<ellipse", "<line", "<polygon", "<polyline", "<g ", "<g>", "transform=", "stroke"):
        if banned in svg:
            sys.exit(f"{svg_file.name}: '{banned.strip()}' isn't supported — write everything as one filled <path>")

    paths = PATH_RE.findall(svg)
    if len(paths) != 1:
        sys.exit(f"{svg_file.name}: expected exactly one <path>, found {len(paths)}")
    d = " ".join(paths[0].split())
    if not ALLOWED_PATH_CHARS.match(d):
        sys.exit(f"{svg_file.name}: path data contains characters VectorDrawable can't parse")
    return TEMPLATE.format(name=name, path=d)


def main() -> int:
    check = "--check" in sys.argv[1:]
    svgs = sorted(SVG_DIR.glob("*.svg"))
    if not svgs:
        sys.exit(f"no SVGs found in {SVG_DIR}")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    stale = []
    for svg in svgs:
        target = OUT_DIR / f"ic_stat_{svg.stem}.xml"
        xml = convert(svg)
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != xml:
                stale.append(target.name)
        else:
            target.write_text(xml, encoding="utf-8", newline="\n")
            print(f"  {svg.name:18s} -> {target.relative_to(HERE.parent.parent)}")

    if check:
        expected = {f"ic_stat_{s.stem}.xml" for s in svgs}
        orphans = sorted(p.name for p in OUT_DIR.glob("ic_stat_*.xml") if p.name not in expected)
        if stale or orphans:
            for n in stale:
                print(f"STALE   {n} (regenerate with build_icons.py)")
            for n in orphans:
                print(f"ORPHAN  {n} (no matching SVG)")
            return 1
        print(f"{len(svgs)} icon(s) up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
